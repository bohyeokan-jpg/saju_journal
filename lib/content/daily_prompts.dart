/// [date]가 주어졌을 때 [element]의 프롬프트 목록에서 그날의 프롬프트
/// 하나를 결정론적으로 고른다 — 같은 날 다시 열어도 같은 질문이, 날짜가
/// 바뀌면 다른 질문이 나오게 하기 위함이다. `DateTime.now()`는 호출부(화면)
/// 에서 주입하고 이 함수는 순수 함수로 둔다.
String promptForDate(WuXing element, DateTime date) {
  final prompts = dailyPrompts[element]!;
  final dayIndex = DateTime(date.year, date.month, date.day)
      .difference(DateTime(2000, 1, 1))
      .inDays;
  final index = ((dayIndex % prompts.length) + prompts.length) % prompts.length;
  return prompts[index];
}
